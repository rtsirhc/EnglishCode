import assert from 'node:assert/strict';
import test from 'node:test';
import { createSession } from '../sentence-showdown/src/lib/session.js';

test('dictation keeps the answer in the teacher snapshot and caps a timeout transfer at the remaining balance', t => {
    t.mock.timers.enable({ apis: ['Date', 'setTimeout'], now: 1000 });
    const game = createSession('CLASS', () => {}, { items: [{ correct: false, text: 'She go home.', correction: 'She goes home.' }] });
    game.join('a', 'Cloud');
    game.join('b', 'River');
    const host = (event, data = {}) => game.command(null, event, data);
    const player = (key, event, data = {}) => game.command(key, event, { turn: game.snapshot().turn, ...data });
    host('start_game');
    host('select_question_type', { type: 'listening' });
    player('p1', 'place_bet', { amount: 100 });
    player('p2', 'place_bet', { amount: 100 });
    host('release_buzzer');
    player('p1', 'buzzer_tap');
    assert.equal(game.snapshot('p1').currentQuestion, null);
    assert.equal(game.snapshot().currentQuestion.sentence, 'She goes home.');
    assert.equal(player('p2', 'host_override').success, false);
    const stale = game.snapshot().turn;
    player('p1', 'submit_answer', { answer: 'Wrong' });
    assert.equal(game.snapshot().players.p1.balance, 900);
    assert.equal(player('p2', 'submit_answer', { turn: stale, answer: 'She goes home.' }).success, false);
    assert.equal(player('p2', 'submit_answer', { answer: 'SHE goes home!' }).isCorrect, true);
    assert.equal(game.snapshot().players.p2.balance, 1200);
    host('next_round');
    host('select_question_type', { type: 'listening' });
    player('p1', 'place_bet', { amount: 100 });
    player('p2', 'place_bet', { amount: 1200 });
    host('release_buzzer');
    player('p1', 'buzzer_tap');
    t.mock.timers.tick(30000);
    assert.equal(game.snapshot().lastResult.amount, 900);
    assert.equal(game.snapshot().winner, 'p2');
    assert.equal(game.snapshot().players.p2.balance, 2100);
    host('new_game');
    assert.equal(game.snapshot().players.p2.balance, 1000);
    game.close();
});

test('speaking allows a new steal after denial and safely returns to the lobby when a player leaves', () => {
    const game = createSession('CLASS', () => {});
    game.join('a', 'Cloud');
    game.join('b', 'River');
    const host = (event, data = {}) => game.command(null, event, data);
    const player = (key, event, data = {}) => game.command(key, event, { turn: game.snapshot().turn, ...data });
    host('start_game');
    host('select_question_type', { type: 'speaking' });
    player('p1', 'place_bet', { amount: 100 });
    player('p2', 'place_bet', { amount: 50 });
    host('release_buzzer');
    player('p1', 'buzzer_tap');
    assert.ok(game.snapshot('p1').currentQuestion.sentence);
    player('p2', 'request_steal');
    host('deny_steal');
    assert.equal(game.snapshot().activePlayer, 'p1');
    player('p2', 'request_steal');
    host('approve_steal');
    host('mark_correct_speaking');
    assert.equal(game.snapshot().players.p2.balance, 1050);
    game.leave('a');
    assert.equal(game.snapshot().phase, 'lobby');
    assert.equal(game.snapshot().players.p2.balance, 1000);
    assert.equal(game.join('c', 'Sun').playerKey, 'p1');
    game.close();
});
